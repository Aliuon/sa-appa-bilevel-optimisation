#!/usr/bin/env python3
"""
run_pipeline.py
================
Single entry point for the SA-APPA supplementary codebase. Ties together
the two halves of the project that were developed as sibling directories
(`sa_appa_experiments/` -- algorithm implementations, benchmark suite,
experiment runner, statistical tests; `sa_appa_figures/` -- figure
generation reading those results) into one command, without changing
either directory's internal layout or relative paths (both packages'
modules assume they sit next to a sibling directory of the other's exact
name, e.g. `sa_appa_figures/real_data.py` reads
`../sa_appa_experiments/results/trajectories.jsonl`).

This does NOT re-implement anything: it is a thin dispatcher that chdirs
into the right subdirectory and calls the existing, already-validated
scripts, so behaviour is identical to running them directly.

Usage
-----
    python3 run_pipeline.py experiments   # run the full 44 x 13 x 30
                                           # experiment sweep (SLOW: this
                                           # is the ~17,160-run sweep that
                                           # took several hours of wall
                                           # time on the machine this was
                                           # developed on; resumable, see
                                           # sa_appa_experiments/run_all.py)
    python3 run_pipeline.py analysis      # run the 7 scenario Friedman
                                           # tests + supplementary analyses
                                           # (feasibility-rate Friedman
                                           # test, constraint-density
                                           # subset + Holm-Bonferroni,
                                           # Scenario 5 tuning diagnostic)
                                           # against results already on disk
    python3 run_pipeline.py figures       # regenerate all figures
                                           # (Figures 1-4, the 44 x 2
                                           # per-instance convergence
                                           # figures, and the 7 CD
                                           # diagrams) from results
                                           # already on disk
    python3 run_pipeline.py all           # experiments -> analysis ->
                                           # figures, in order

Fast path for reviewers or readers who just want to regenerate the
figures and tables from the results already shipped in
sa_appa_experiments/results/ (summary.csv, trajectories.jsonl,
scenario_cd_summaries.json, etc.) without re-running several hours of
optimisation:

    python3 run_pipeline.py figures

This is almost always what you want. `experiments` is only needed to
regenerate the raw results themselves from scratch (e.g. after changing
an algorithm implementation), and even then is resumable rather than
all-or-nothing (see sa_appa_experiments/run_all.py's module docstring).

Requirements: see requirements.txt at this package's root (numpy, pandas,
scipy, matplotlib). Tested with Python 3.11.
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
EXPERIMENTS_DIR = os.path.join(ROOT, "sa_appa_experiments")
FIGURES_DIR = os.path.join(ROOT, "sa_appa_figures")

FIGURES_STAGE_SCRIPT = '''\
"""
Auto-generated by run_pipeline.py's `figures` stage. Regenerates every
figure embedded in or referenced by the manuscript: Figures 1, 2, 2b
(tau=0.1 and tau=0.25), the full 44-instance Figures 3 and 4, and the 7
per-scenario critical-difference diagrams (fig:cd1--fig:cd7).
"""
from real_data import load_real_results
from benchmark import SUITE
from figures.fig1_boxplot import make_figure1
from figures.fig2_performance_profile import make_figure2
from figures.fig2b_data_profile import make_figure2b
from figures.fig3_convergence_curves import make_figure3_all
from figures.fig4_convergence_rate import make_figure4_all
from figures.fig5_cd_diagram_scenarios import make_all_cd_diagrams
from config import METHOD_IDS

df = load_real_results()
out_dir = "output_real"
make_figure1(df, out_dir, method_ids=METHOD_IDS, is_synthetic=False, n_runs=30)
make_figure2(df, out_dir, method_ids=METHOD_IDS, is_synthetic=False)
make_figure2b(df, out_dir, SUITE, method_ids=METHOD_IDS, is_synthetic=False, tau=0.1)
make_figure2b(df, out_dir, SUITE, method_ids=METHOD_IDS, is_synthetic=False, tau=0.25)
make_figure3_all(df, out_dir, method_ids=METHOD_IDS, is_synthetic=False, n_runs=30)
make_figure4_all(df, out_dir, method_ids=METHOD_IDS, is_synthetic=False, n_runs=30)
make_all_cd_diagrams("scenario_cd_summaries.json", out_dir, is_synthetic=False)
print("All figures written to", out_dir)
'''


def _run(cmd, cwd, env=None):
    print(f"\\n$ (cwd={os.path.relpath(cwd, ROOT)}) {' '.join(cmd)}")
    result = subprocess.run(cmd, cwd=cwd, env=env)
    if result.returncode != 0:
        print(f"[run_pipeline] command failed with exit code {result.returncode}: {cmd}",
              file=sys.stderr)
        sys.exit(result.returncode)


def stage_experiments():
    """Full 44-instance x 13-method x 30-run sweep. Resumable -- see
    sa_appa_experiments/run_all.py's module docstring; safe to interrupt
    and re-invoke."""
    _run([sys.executable, "run_all.py"], cwd=EXPERIMENTS_DIR)


def stage_analysis():
    """The 7 per-scenario Friedman tests (Appendix B), the supplementary
    analyses added after scenario sign-off (feasibility-rate Friedman
    test, constraint-density subset + Holm-Bonferroni, Scenario 5 tuning
    diagnostic -- Appendix D), and the JSON export the CD diagrams read."""
    _run([sys.executable, "analysis.py"], cwd=EXPERIMENTS_DIR)
    _run([sys.executable, "analysis_extra.py"], cwd=EXPERIMENTS_DIR)
    _run([sys.executable, "export_scenario_summaries.py"], cwd=EXPERIMENTS_DIR)


def stage_figures():
    """Regenerates every figure embedded in or referenced by the
    manuscript. Needs sa_appa_experiments/ on sys.path (for `benchmark`
    and the Nemenyi/Friedman results it reads), which is handled here via
    PYTHONPATH rather than duplicating benchmark.py into sa_appa_figures/."""
    stage_path = os.path.join(FIGURES_DIR, "_pipeline_stage.py")
    with open(stage_path, "w") as f:
        f.write(FIGURES_STAGE_SCRIPT)
    env = os.environ.copy()
    env["PYTHONPATH"] = EXPERIMENTS_DIR + os.pathsep + env.get("PYTHONPATH", "")
    try:
        _run([sys.executable, "_pipeline_stage.py"], cwd=FIGURES_DIR, env=env)
    finally:
        if os.path.exists(stage_path):
            os.remove(stage_path)


STAGES = {
    "experiments": stage_experiments,
    "analysis": stage_analysis,
    "figures": stage_figures,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("stage", choices=list(STAGES) + ["all"])
    args = parser.parse_args()

    if args.stage == "all":
        stage_experiments()
        stage_analysis()
        stage_figures()
    else:
        STAGES[args.stage]()


if __name__ == "__main__":
    main()
